// IsPublicIP reports whether ip is a globally routable address suitable for a
// public CA validation attempt. It deliberately rejects IANA documentation,
// benchmarking, shared-address, transition, and other special-purpose ranges
// in addition to the private ranges recognized by net.IP.
func IsPublicIP(ip net.IP) bool {
	address, ok := netip.AddrFromSlice(ip)
	if !ok {
		return false
	}
	address = address.Unmap()
	if !address.IsGlobalUnicast() || address.IsPrivate() ||
		address.IsLoopback() || address.IsLinkLocalUnicast() ||
		address.IsLinkLocalMulticast() || address.IsUnspecified() {
		return false
	}
	for _, prefix := range nonPublicPrefixes {
		if prefix.Contains(address) {
			return false
		}
	}
	return true
}
